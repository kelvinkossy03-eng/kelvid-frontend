function ShowcasePlayer() {
  const [index, setIndex] = useState(0)
  const [typed, setTyped] = useState('')
  const [playing, setPlaying] = useState(true)

  const scene = SCENES[index]

  useEffect(() => {
    if (!playing) return undefined
    const rotate = setInterval(() => {
      setIndex((i) => (i + 1) % SCENES.length)
    }, 7000)
    return () => clearInterval(rotate)
  }, [playing, index])

  useEffect(() => {
    setTyped('')
    if (!playing) return undefined
    let i = 0
    const t = setInterval(() => {
      i += 1
      setTyped(scene.prompt.slice(0, i))
      if (i >= scene.prompt.length) clearInterval(t)
    }, 26)
    return () => clearInterval(t)
  }, [scene.prompt, playing])

  return (
    <div className="showcase glass-card" aria-label="Preview of videos generated by Kelvid Studio">
      <div className="showcase-stage">
        <div className={`scene scene-${scene.id} ${playing ? '' : 'paused'}`} key={scene.id} />
        <div className="scene-grain" />
        <div className="scene-letterbox" />
        <div className="showcase-hud">
          <span className="hud-dot" />
          <span className="hud-label">LIVE PREVIEW</span>
          <span className="hud-meta">{scene.meta}</span>
        </div>
        <button
          type="button"
          className="showcase-toggle"
          onClick={() => setPlaying((p) => !p)}
          aria-label={playing ? 'Pause preview' : 'Play preview'}
        >
          {playing ? '❚❚' : '▶'}
        </button>
      </div>
      <div className="showcase-caption">
        <div className="showcase-prompt">
          <span className="prompt-tag">prompt</span>
          <span className="typed">{typed}</span>
          <span className="caret" />
        </div>
        <div className="showcase-bar">
          <div
            className={`showcase-bar-fill ${playing ? '' : 'paused'}`}
            key={`bar-${scene.id}`}
          />
        </div>
        <div className="showcase-thumbs">
          {SCENES.map((s, i) => (
            <button
              key={s.id}
              type="button"
              className={`thumb thumb-${s.id} ${i === index ? 'active' : ''}`}
              onClick={() => setIndex(i)}
              aria-label={`Show preview: ${s.label}`}
            />
          ))}
        </div>
      </div>
    </div>
  )
}
